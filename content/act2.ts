/** 2막 다섯 장. 고민을 골랐으면 2장 맨 앞에 그 답을 넣는다(1막 편지: "그 답부터 말해줄게") */
export function chapters(status: string, strong: boolean, worry = ''): Chapter[] {
  const g = groupOf(status), together = g === 'together';
  const ch2 = { ...CH2[g], items: [...CH2[g].items] };
  if (worry) ch2.items.unshift([`“${worry}”`, '네가 물어본 고민에 대한 노엘의 답']);
  if (worry) ch2.hint = `“${worry}”, 그 답과 근거`;
  return [CH1, ch2, together ? CH3_TOGETHER : CH3, CH4(strong), CH5];
}

